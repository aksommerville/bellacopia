/* Search planes.
 */
 
const int plane_contains_mapid(int *lng,int *lat,const struct plane *plane,int mapid) {
  const uint16_t *v=plane->v;
  int c=plane->w*plane->h;
  int i=c;
  for (;i-->0;v++) if (*v==mapid) {
    if (lng) *lng=(c-i-1)%plane->w;
    if (lat) *lat=(c-i-1)/plane->w;
    return 1;
  }
  return 0;
}
 
const struct plane *plane_for_mapid(int *lng,int *lat,int mapid) {
  const struct plane *plane=planev;
  int i=PLANEC;
  for (;i-->0;plane++) {
    if (plane_contains_mapid(lng,lat,plane,mapid)) return plane;
  }
  return 0;
}
